"""
============================================================================
 pca.py(詳細註解版)— 用 PCA 把「9 個數字」壓成「2 個數字」
============================================================================
這個檔給「完全沒寫過 Python」的同學。每一行都會解釋在做什麼。
你只要從上往下讀,就能看懂「把資料壓縮再還原」整件事。

PCA 是三種方法裡最簡單的:它不用「訓練」,用一次數學運算就把答案算出來。
直接在終端機輸入:  python pca.py

⚠️ 資料注意:本範例與 pretrained/ 的模型,用的是 repo 內的「示範資料」
   (v03/cache/cells.parquet),那不是最完整、最正確的原始資料。
   等正式資料(由上游依 ../../06_INTERFACE_HANDOFF.md 整理)到位後,
   一定要把設定區的 DATA 改成正式資料的路徑、重新跑一次,
   這裡印出的數字與存下的模型才有效。
============================================================================
"""

# --- import:把別人寫好的工具箱拿進來用 ---
import os               # os:處理「檔案路徑」(電腦裡檔案放哪)的工具
import numpy as np      # numpy:處理「一堆數字(矩陣)」的工具,之後簡稱 np
import pandas as pd     # pandas:讀「表格檔」的工具,之後簡稱 pd


# ============================================================
# 設定區:可以調整的參數都放最上面,方便修改
# ============================================================

# __file__ 是「這個 .py 檔自己的位置」。下面這行算出本檔所在的資料夾。
HERE = os.path.dirname(os.path.abspath(__file__))

# 從本檔往上跳 4 層資料夾,找到專案根目錄裡的資料表。
# (本檔在 code/detailed/ 裡,往上 4 層到專案根,再進 v03/cache/)
DATA = os.path.join(HERE, "..", "..", "..", "..", "v03", "cache", "cells.parquet")

# 存放輸出(圖、結果)的資料夾;若不存在就建一個。
OUT = os.path.join(HERE, "..", "outputs")
os.makedirs(OUT, exist_ok=True)

# 要用哪些欄位當「channel」(每格的數字)?
# 我們不限制上游給幾個。CHANNELS = None 表示「自動使用表格裡所有數值欄」,
# 不管它給 9 個還是 30 個都行;要手動指定就把 CHANNELS 填成一個欄名 list。
CHANNELS = None
# 下面這些是「不是 channel 的欄」(位置、名稱、幾何、舊標籤等),會自動跳過。
NON_CHANNEL = {"window", "row", "col", "role", "name", "geometry", "bid", "bidx",
               "n_bld", "token", "token_v03", "token_v04", "judge", "semantic", "family"}

LATENT = 2          # 要壓成幾個數字。設 2 是因為 2 維才畫得出散點圖。


# ============================================================
# 第 1 步:把表格讀進來,並丟掉「空格子」
# ============================================================

# pd.read_parquet(...) 把硬碟上的表格檔讀成一個「DataFrame」(就是一張表)。
df = pd.read_parquet(DATA)

# 如果表格裡有「覆蓋率 coverage」欄,就把空地(覆蓋率<0.02)的格子丟掉。
# (用 if 包起來:萬一上游沒給 coverage 這欄,也不會出錯。)
if "coverage" in df.columns:
    df = df[df["coverage"] >= 0.02].reset_index(drop=True)

# 自動決定要用哪些欄當 channel:
#   若有手動指定 CHANNELS 就用它;否則挑出「所有數值欄,但不在 NON_CHANNEL 名單裡」的欄。
# pd.api.types.is_numeric_dtype(...) 用來判斷某一欄是不是數字欄。
FEATS = CHANNELS or [c for c in df.columns
                     if c not in NON_CHANNEL and pd.api.types.is_numeric_dtype(df[c])]

# df[FEATS] 取出那些欄。.to_numpy(...) 把表格轉成 numpy 的數字矩陣。
# X 的形狀(shape)是 [N, C]:N 列(N 個格子),每列 C 個數字(C = channel 數)。
X = df[FEATS].to_numpy(np.float32)

N = len(X)                          # len(X) = 列數 = 格子數 N
print(f"資料筆數 N={N}，每筆 C={len(FEATS)} 個數字")
print(f"自動選到的 channel:{FEATS}")


# ============================================================
# 第 2 步:把資料分成「訓練組」和「驗證組」
# ============================================================
# 為什麼要分?訓練組用來「算模型」,驗證組用來「檢查模型對沒看過的資料好不好」。

rng = np.random.default_rng(0)      # 建一個亂數產生器,種子設 0(每次結果都一樣,可重現)
idx = rng.permutation(N)            # 把 0..N-1 的順序「洗牌」
va = idx[:N // 5]                   # 前 1/5 當驗證組(va = validation)
tr = idx[N // 5:]                   # 其餘 4/5 當訓練組(tr = train)


# ============================================================
# 第 3 步:標準化(把每個數字拉到同一個尺度)
# ============================================================
# 問題:gfa 可以到好幾萬,coverage 只有 0~1。直接用,大數字會「霸佔」運算。
# 解法:每一欄各自做 (數值 - 平均) / 標準差,讓每欄都變成「平均 0、散開 1」。

mean = X[tr].mean(0)               # 每一欄的平均(只用訓練組算,避免偷看驗證組)
std = X[tr].std(0)                 # 每一欄的標準差(散開程度)
std[std == 0] = 1                  # 萬一某欄都一樣(std=0),把它設 1,避免除以 0 出錯
Xz = (X - mean) / std             # 標準化後的資料,形狀還是 [N, 9]


# ============================================================
# 第 4 步:PCA 的核心 —— 用 SVD 找出「最佳壓縮方向」
# ============================================================
# 直覺:9 維資料像一團雲。PCA 找出這團雲「最長的兩個方向」,沿著它們拍照最不失真。

Xc = Xz[tr] - Xz[tr].mean(0)       # 再置中一次(保險:讓平均剛好在原點)

# np.linalg.svd 是「奇異值分解」,一行數學就把最佳方向算出來。
# 它回傳三個東西,我們只需要 Vt(裡面藏著方向)和 S(每個方向有多長)。
U, S, Vt = np.linalg.svd(Xc, full_matrices=False)

# Vt[:LATENT] 取前 2 個方向;.T 是「轉置」(把列變行),讓 W 形狀變成 [9, 2]。
# W 就是「編碼器」——它其實只是一個矩陣。
W = Vt[:LATENT].T

# 算這 2 個方向各「抓住了多少比例的資訊」(解釋變異),越高越好。
explained = (S[:LATENT] ** 2) / (S ** 2).sum()
print(f"編碼矩陣 W 形狀 = {W.shape}")
print(f"兩個方向各抓住的資訊比例 = {np.round(explained, 3)}")


# ============================================================
# 第 5 步:編碼(壓縮)與解碼(還原)
# ============================================================
# @ 是「矩陣相乘」。

Z = Xz @ W          # 編碼:[N,9] 乘 [9,2] = [N,2]。每個格子變成 2 個數字。這就是壓縮結果。
Xhat = Z @ W.T      # 解碼:[N,2] 乘 [2,9] = [N,9]。從 2 個數字還原回 9 個。Xhat 念作 "X hat"。


# ============================================================
# 第 6 步:看「還原得像不像」(重建誤差)
# ============================================================
# 重建誤差 = 原本和還原後的差距平方的平均。越小代表壓縮時丟掉的資訊越少。

def err(a, b):
    return float(np.mean((a - b) ** 2))     # (a-b) 的平方,再取平均

print(f"重建誤差  訓練組={err(Xz[tr], Xhat[tr]):.4f}   驗證組={err(Xz[va], Xhat[va]):.4f}")
print("(這個數字之後會跟 AE、VAE 比;PCA 通常是三者裡最大的,因為它只能直線壓)")


# ============================================================
# 第 7 步:把壓縮結果存檔,並畫成散點圖
# ============================================================

# 把編碼矩陣 W 和壓縮結果 Z 存成一個檔,之後可以再拿出來用。
np.savez(os.path.join(OUT, "pca_result.npz"), W=W, Z=Z)

# 畫圖需要 matplotlib;萬一沒安裝,用 try/except 包起來,沒裝也不會讓程式壞掉。
try:
    import matplotlib
    matplotlib.use("Agg")               # "Agg" 表示「不開視窗,直接存成圖檔」
    import matplotlib.pyplot as plt

    plt.figure(figsize=(5, 5))          # 開一張 5x5 吋的畫布
    # scatter 畫散點:x 座標用 Z 第 0 欄,y 座標用 Z 第 1 欄。
    # s=4 點的大小,alpha=.4 半透明(點重疊時看得出濃淡)。
    plt.scatter(Z[:, 0], Z[:, 1], s=4, alpha=.4)
    plt.xlabel("PC1")                   # x 軸標籤
    plt.ylabel("PC2")                   # y 軸標籤
    plt.title("PCA latent")             # 圖標題
    plt.tight_layout()                  # 自動排版,避免文字被切掉
    plt.savefig(os.path.join(OUT, "pca_latent.png"), dpi=120)   # 存成 png
    print("已存圖 → outputs/pca_latent.png")
except ImportError:
    print("(沒裝 matplotlib,跳過畫圖。數字已經印在上面了。)")
